const src = (page: number, section: string, item?: string) => ({ page, section, item });

const teach = (id: string, page: number, title: string, content: string, mathFormula?: string): ContentBlock => ({
  id,
  type: 'teach',
  authored: true,
  title: `🧠 ${title}`,
  sourceRef: src(page, 'شرح المنصة'),
  content,
  mathFormula,
});

const insight = (id: string, page: number, title: string, content: string, mathFormula?: string): ContentBlock => ({
  id,
  type: 'insight',
  authored: true,
  title: `💡 ${title}`,
  sourceRef: src(page, 'شرح المنصة'),
  content,
  mathFormula,
});

const mistake = (id: string, page: number, title: string, content: string): ContentBlock => ({
  id,
  type: 'mistake',
  authored: true,
  title: `⚠️ ${title}`,
  sourceRef: src(page, 'شرح المنصة'),
  content,
});

const example = (
  id: string,
  page: number,
  item: string | undefined,
  title: string,
  content: string,
  mathFormula?: string,
  solution?: string,
): ContentBlock => ({
  id,
  type: 'example',
  title,
  sourceRef: src(page, 'مثال من الكتاب', item),
  content,
  mathFormula,
  // الشرح المصاحب لمثال الكتاب من إعداد المنصة، فيُعلَّم بذلك صريحًا.
  explanation: solution ? `**شرح المنصة:** ${solution}` : undefined,
});

